// 한글 본문 줄바꿈 보호 — 렌더 타임 전용(원본 콘텐츠는 변형하지 않는다).
//
// 전역 word-break: keep-all 은 "어절"만 보호한다. 가운뎃점(·)으로 이어진 복합어는
// · 뒤가 줄바꿈 기회라 "바이오·/포토닉스"처럼 갈라지고, "(현 입학정원 180명)" 같은
// 짧은 괄호 부가어도 중간에서 접힌다. CSS 로는 막을 수 없어(line-break 속성은 ·에
// 관여하지 않는다) 문자열 단계에서 보이지 않는 결합 문자를 끼워 막는다.
//
// 저작 규약은 "규약 없음"이다 — CMS 편집자·번역자는 평범하게 타이핑하면 되고,
// 보호는 렌더 지점에서 이 함수를 명시 호출해 적용한다. pick() 안에 넣지 않는 이유:
// pick 은 URL·이메일·첨부 라벨 같은 비본문에도 쓰여 부작용 범위를 가늠할 수 없다.

/** 괄호 부가어를 한 덩어리로 묶는 최대 내용 길이 — 이보다 길면 좁은 화면에서
 *  오버플로가 나므로 그대로 둔다(전역 overflow-wrap 이 최후 방어). */
const PAREN_MAX = 14;

/** WORD JOINER — 폭 0, 줄바꿈 기회 제거. 리터럴로 두면 에디터에서 안 보여 사고가
 *  나기 쉬워 이스케이프로 명시한다. */
const WJ = '\u2060';
/** NO-BREAK SPACE — 공백 폭 유지 + 줄바꿈 금지 */
const NBSP = '\u00A0';

/**
 * 1) 가운뎃점 복합어: · 뒤에 WORD JOINER 를 끼워 줄바꿈 기회를 없앤다.
 * 2) 짧은 괄호 부가어(내용 2~14자): 내부 공백을 NBSP 로 바꿔 통째로 움직이게 한다.
 */
export function guardKoreanBreaks(text: string): string {
  return text
    .replace(/(\S)·(?=\S)/g, `$1·${WJ}`)
    .replace(new RegExp(`\\(([^()\\n]{2,${PAREN_MAX}})\\)`, 'g'), (_whole, inner: string) =>
      `(${inner.replace(/ /g, NBSP)})`,
    );
}
